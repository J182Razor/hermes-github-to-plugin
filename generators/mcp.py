from __future__ import annotations

import json
import os
import shutil
from pathlib import Path
from typing import Any, Dict


def generate(repo_path: str, out_dir: str, name: str, report: dict) -> dict:
    root = Path(repo_path)
    out = Path(out_dir) / name
    out.mkdir(parents=True, exist_ok=True)

    # plugin.json
    plugin_json = {
        "$schema": "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json",
        "name": name,
        "version": "1.0.0",
        "description": f"Hermes plugin generated from {report.get('repo_url', repo_path)}",
        "author": {"name": "BlueStarJL"},
        "license": "MIT",
        "homepage": report.get("repo_url", ""),
        "keywords": ["mcp", "generated", "github-to-hermes"],
        "extensions": {"com.nousresearch.hermes": {"servers": {}}},
    }
    (out / "plugin.json").write_text(json.dumps(plugin_json, indent=2), encoding="utf-8")

    # mcp.json: try to copy source mcp.json, else build from entrypoints
    src_mcp = root / "mcp.json"
    mcp_servers = {}
    if src_mcp.is_file():
        try:
            data = json.loads(src_mcp.read_text(encoding="utf-8"))
            mcp_servers = data.get("mcpServers", {}) or {}
        except Exception:
            mcp_servers = {}
    if not mcp_servers:
        # fallback stdio using first entrypoint or npx
        entry = (report.get("entrypoints") or ["server/index.js"])[0]
        mcp_servers = {
            name: {
                "type": "stdio",
                "command": "node",
                "args": [entry],
            }
        }
    # pass env vars through as ${VAR}
    for sname, scfg in mcp_servers.items():
        if "env" not in scfg:
            scfg["env"] = {}
        for v in report.get("env_vars", []):
            if v not in scfg["env"]:
                scfg["env"][v] = f"${{{v}}}"
    mcp_json = {"$schema": "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json", "mcpServers": mcp_servers}
    (out / "mcp.json").write_text(json.dumps(mcp_json, indent=2), encoding="utf-8")

    # trust untrusted for doop-like? Generic: leave default; user can set. We'll add extension trust if remote
    # Update extensions servers with trust untrusted for streamable-http
    ext_servers = {}
    for sname, scfg in mcp_servers.items():
        if scfg.get("type") == "streamable-http":
            ext_servers[sname] = {"trust": "untrusted"}
    if ext_servers:
        plugin_json["extensions"]["com.nousresearch.hermes"]["servers"] = ext_servers
        (out / "plugin.json").write_text(json.dumps(plugin_json, indent=2), encoding="utf-8")

    # skills
    skills_dir = out / "skills" / name
    skills_dir.mkdir(parents=True, exist_ok=True)
    readme = ""
    for rn in ("README.md",):
        if (root / rn).is_file():
            readme = (root / rn).read_text(encoding="utf-8", errors="ignore")
            break
    skill_md = f"""---
name: {name}
description: MCP-backed plugin generated from {report.get('repo_url', '')}. Use the bundled MCP server tools.
---

# {name}

Generated by github-to-hermes from {report.get('repo_url', '')}.

## Usage

{readme[:2000] if readme else 'See source repository README.'}

## Hermes notes

- MCP server declared in mcp.json.
- Set required environment variables before use.
"""
    (skills_dir / "SKILL.md").write_text(skill_md, encoding="utf-8")

    # README
    (out / "README.md").write_text(
        f"# {name}\n\nGenerated by github-to-hermes.\n\nSource: {report.get('repo_url', '')}\n\n"
        "## Install\n\n`hermes plugins install /path/to/this/dir --enable`\n\n"
        "## Disclosure\n\nNetwork calls to the configured MCP server. Credentials via Hermes secret routes.\n",
        encoding="utf-8",
    )
    return {"output_path": str(out), "files": sorted(str(p.relative_to(out)) for p in out.rglob("*") if p.is_file())}
